// Builds a MySQL script that makes a target schema match a source schema, from a computed diff.
// The script is shown to the user and only runs through the normal write confirmation.
import type { ColumnInfo, DatabaseSchema, ForeignKeyInfo, IndexInfo, ObjectDiff, SchemaDiff, SyncScript, TableDiff } from '../../shared/model';
import { quoteIdent } from './identifiers';
import { formatLiteral } from './literals';

export interface SyncInput {
  diff: SchemaDiff;
  source: DatabaseSchema;
  target: DatabaseSchema;
  /** SHOW CREATE TABLE output for source tables that are missing in the target. */
  createStatements: ReadonlyMap<string, string>;
  /** Source table names to include; all differing tables when omitted. */
  tables?: readonly string[];
  /** Also drop tables, columns, indexes and foreign keys that exist only in the target. */
  includeDrops: boolean;
}

const NUMERIC = /^(tinyint|smallint|mediumint|int|integer|bigint|decimal|numeric|float|double|real|bit|year)$/;
const TIMESTAMP_FN = /^current_timestamp(\(\d*\))?$/i;

function defaultSql(c: ColumnInfo): string {
  const d = c.defaultValue!;
  if (/default_generated/i.test(c.extra)) return TIMESTAMP_FN.test(d) ? d.toUpperCase() : `(${d})`;
  if (TIMESTAMP_FN.test(d)) return d.toUpperCase();
  if (/^'.*'$/s.test(d) || /^b'[01]*'$/i.test(d)) return d; // MariaDB reports literals already quoted
  if (NUMERIC.test(c.dataType) && /^-?\d+(\.\d+)?([eE][-+]?\d+)?$/.test(d)) return d;
  return formatLiteral(d, 'mysql');
}

/** A column definition for ADD/MODIFY COLUMN, or undefined for generated columns (their expression is not loaded). */
export function columnDefinition(c: ColumnInfo): string | undefined {
  const extra = c.extra.toLowerCase();
  if (/\b(virtual|stored) generated\b/.test(extra)) return undefined;
  const parts = [quoteIdent(c.name), c.columnType, c.nullable ? 'NULL' : 'NOT NULL'];
  if (c.defaultValue !== null && !(c.nullable && /^null$/i.test(c.defaultValue))) parts.push(`DEFAULT ${defaultSql(c)}`);
  if (c.isAutoIncrement) parts.push('AUTO_INCREMENT');
  const onUpdate = /on update (current_timestamp(\(\d*\))?)/i.exec(c.extra);
  if (onUpdate) parts.push(`ON UPDATE ${onUpdate[1]!.toUpperCase()}`);
  if (c.comment) parts.push(`COMMENT ${formatLiteral(c.comment, 'mysql')}`);
  return parts.join(' ');
}

const identList = (names: readonly string[]) => names.map((n) => quoteIdent(n)).join(', ');

function addIndexClause(i: IndexInfo): string {
  if (i.primary) return `ADD PRIMARY KEY (${identList(i.columns)})`;
  const type = (i.type || '').toUpperCase();
  const kind = type === 'FULLTEXT' ? 'FULLTEXT INDEX' : type === 'SPATIAL' ? 'SPATIAL INDEX' : i.unique ? 'UNIQUE INDEX' : 'INDEX';
  return `ADD ${kind} ${quoteIdent(i.name)} (${identList(i.columns)})`;
}

const dropIndexClause = (name: string, primary: boolean) => (primary ? 'DROP PRIMARY KEY' : `DROP INDEX ${quoteIdent(name)}`);

function addForeignKey(fk: ForeignKeyInfo): string {
  const ref = fk.referencedDatabase && fk.referencedDatabase !== fk.database ? `${quoteIdent(fk.referencedDatabase)}.${quoteIdent(fk.referencedTable)}` : quoteIdent(fk.referencedTable);
  return `ADD CONSTRAINT ${quoteIdent(fk.name)} FOREIGN KEY (${identList(fk.columns)}) REFERENCES ${ref} (${identList(fk.referencedColumns)}) ON DELETE ${fk.onDelete} ON UPDATE ${fk.onUpdate}`;
}

/** Orders new tables so that tables referenced by foreign keys are created first. */
function creationOrder(tables: string[], source: DatabaseSchema): string[] {
  const set = new Set(tables);
  const deps = new Map(tables.map((t) => [t, source.foreignKeys.filter((fk) => fk.table === t && set.has(fk.referencedTable) && fk.referencedTable !== t).map((fk) => fk.referencedTable)]));
  const out: string[] = [];
  const state = new Map<string, 'visiting' | 'done'>();
  const visit = (t: string) => {
    if (state.get(t)) return; // done, or a cycle: keep the order we have
    state.set(t, 'visiting');
    for (const d of deps.get(t) ?? []) visit(d);
    state.set(t, 'done');
    out.push(t);
  };
  tables.forEach(visit);
  return out;
}

export function buildSyncScript(input: SyncInput): SyncScript {
  const { diff, source, target, includeDrops } = input;
  const statements: string[] = [];
  const warnings: string[] = [];
  const lines: string[] = [
    `-- Make ${diff.target.database} (target) match ${diff.source.database} (source).`,
    `-- Generated by DeepDive on ${new Date(diff.comparedAt).toISOString()}. Review before running:`,
    '-- MySQL commits schema changes immediately; they cannot be rolled back.',
  ];
  // Section headers are written lazily, so empty sections leave no trace.
  let pendingSection: string | undefined;
  const flush = () => {
    if (pendingSection) lines.push('', `-- ${pendingSection}`);
    pendingSection = undefined;
  };
  const emit = (sql: string) => {
    flush();
    statements.push(sql);
    lines.push(`${sql};`);
  };
  const note = (text: string) => {
    flush();
    lines.push(`-- ${text}`);
  };
  const warn = (text: string) => {
    warnings.push(text);
    note(text);
  };
  const section = (title: string) => (pendingSection = `== ${title} ==`);
  const skippedDrop = (what: string) => note(`Skipped: ${what} exists only in the target (enable "Include drops" to remove it).`);

  const wanted = input.tables ? new Set(input.tables) : undefined;
  const selected = diff.tables.filter((t) => t.status !== 'same' && (!wanted || wanted.has(t.name)));
  const targetTable = (t: TableDiff) => quoteIdent(t.targetName ?? t.name);
  const srcCols = (table: string) => source.columns.filter((c) => c.table === table).sort((a, b) => a.ordinal - b.ordinal);
  const srcIndex = (table: string, name: string) => source.indexes.find((i) => i.table === table && i.name === name);
  const srcFk = (table: string, name: string) => source.foreignKeys.find((f) => f.table === table && f.name === name);
  const tgtIndex = (t: TableDiff, d: ObjectDiff) => target.indexes.find((i) => i.table === (t.targetName ?? t.name) && i.name === (d.targetName ?? d.name));
  const changed = selected.filter((t) => t.status === 'changed');

  // 1. Foreign keys go first, so columns and indexes they depend on can change.
  section('Foreign keys to drop or redefine');
  for (const t of changed) {
    for (const d of t.foreignKeys) {
      if (d.status === 'changed' && !d.targetName) emit(`ALTER TABLE ${targetTable(t)} DROP FOREIGN KEY ${quoteIdent(d.name)}`);
      else if (d.status === 'changed') note(`${t.name}: foreign key ${d.targetName} matches ${d.name} except for its name; left as is.`);
      else if (d.status === 'only_target') {
        if (includeDrops) emit(`ALTER TABLE ${targetTable(t)} DROP FOREIGN KEY ${quoteIdent(d.name)}`);
        else skippedDrop(`${t.name}: foreign key ${d.name}`);
      }
    }
  }

  // 2. Tables that exist only in the target.
  const extraTables = selected.filter((t) => t.status === 'only_target');
  section('Tables that exist only in the target');
  for (const t of extraTables) {
    if (includeDrops) emit(`DROP ${t.type === 'view' ? 'VIEW' : 'TABLE'} ${quoteIdent(t.name)}`);
    else skippedDrop(`${t.type} ${t.name}`);
  }

  // 3. Tables that exist only in the source.
  const missing = selected.filter((t) => t.status === 'only_source');
  section('Tables missing in the target');
  for (const t of missing.filter((x) => x.type === 'view')) warn(`View ${t.name} exists only in the source. View definitions are not compared; create it manually.`);
  for (const name of creationOrder(missing.filter((x) => x.type === 'table').map((x) => x.name), source)) {
    const ddl = input.createStatements.get(name);
    if (!ddl) {
      warn(`Could not read the definition of ${name}; create it manually.`);
      continue;
    }
    emit(ddl.replace(/\s+AUTO_INCREMENT=\d+/i, ''));
  }

  // 4. Tables on both sides.
  section('Tables to alter');
  for (const t of changed) {
    if (t.changes.some((c) => c.field === 'type')) {
      warn(`${t.name} is a ${t.type} in the source but not in the target; convert it manually.`);
      continue;
    }
    if (t.type === 'view') continue;
    const clauses: string[] = [];
    const cols = srcCols(t.name);
    const position = (name: string) => {
      const i = cols.findIndex((c) => c.name === name);
      return i <= 0 ? 'FIRST' : `AFTER ${quoteIdent(cols[i - 1]!.name)}`;
    };
    for (const d of t.indexes) {
      if (d.status === 'changed' && !d.targetName) clauses.push(dropIndexClause(d.name, Boolean(tgtIndex(t, d)?.primary)));
      if (d.status === 'only_target') {
        if (includeDrops) clauses.push(dropIndexClause(d.name, Boolean(tgtIndex(t, d)?.primary)));
        else skippedDrop(`${t.name}: index ${d.name}`);
      }
    }
    for (const d of t.columns.filter((c) => c.status === 'only_target')) {
      if (includeDrops) clauses.push(`DROP COLUMN ${quoteIdent(d.name)}`);
      else skippedDrop(`${t.name}: column ${d.name}`);
    }
    for (const d of t.columns) {
      if (d.status !== 'only_source' && d.status !== 'changed') continue;
      const col = cols.find((c) => c.name === d.name)!;
      const def = columnDefinition(col);
      if (!def) {
        warn(`${t.name}.${d.name} is a generated column; its expression is not available, so add or change it manually.`);
        continue;
      }
      if (d.status === 'only_source') clauses.push(`ADD COLUMN ${def} ${position(d.name)}`);
      else clauses.push(`MODIFY COLUMN ${def}${d.changes.some((c) => c.field === 'position') ? ` ${position(d.name)}` : ''}`);
    }
    for (const d of t.indexes) {
      if (d.status === 'changed' && d.targetName) {
        if (d.changes.length === 1) clauses.push(`RENAME INDEX ${quoteIdent(d.targetName)} TO ${quoteIdent(d.name)}`);
        continue;
      }
      if (d.status !== 'only_source' && d.status !== 'changed') continue;
      const idx = srcIndex(t.name, d.name);
      if (idx) clauses.push(addIndexClause(idx));
    }
    for (const c of t.changes) {
      if (c.field === 'engine' && c.source) clauses.push(`ENGINE=${c.source}`);
      if (c.field === 'comment') clauses.push(`COMMENT=${formatLiteral(c.source ?? '', 'mysql')}`);
    }
    if (clauses.length) emit(`ALTER TABLE ${targetTable(t)}\n  ${clauses.join(',\n  ')}`);
  }

  // 5. Foreign keys last, once every table, column and index they need exists.
  const fkAdds = changed.flatMap((t) =>
    t.foreignKeys.filter((d) => (d.status === 'only_source' || d.status === 'changed') && !d.targetName).flatMap((d) => {
      const fk = srcFk(t.name, d.name);
      return fk ? [`ALTER TABLE ${targetTable(t)} ${addForeignKey(fk)}`] : [];
    }),
  );
  section('Foreign keys to add');
  fkAdds.forEach(emit);

  if (statements.length === 0) lines.push('', '-- Nothing to run for the selected tables.');
  return { script: lines.join('\n'), statements, warnings };
}
